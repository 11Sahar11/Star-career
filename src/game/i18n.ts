const tables: Record<Lang, Record<string, string>> = { en, he, es, fr };

export function t(key: string, vars?: Record<string, string | number>, lang: Lang = current): string {
  const table = tables[lang] ?? en;
  let text = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function show(raw: string, lang: Lang = current): string {
  if (!raw || !raw.startsWith("@")) return raw;
  const body = raw.slice(1);
  const hash = body.indexOf("#");
  const main = hash >= 0 ? body.slice(0, hash) : body;
  const index = hash >= 0 ? Number(body.slice(hash + 1)) : -1;
  const parts = main.split("|");
  const key = parts[0] ?? "";
  const a = parts[1] ?? "";
  const b = parts[2] ?? "";
  const named = (value: string) => (value.includes(".") ? t(value, undefined, lang) : value);
  const name = named(a);
  const second = ["Quarter-final", "Semi-final", "Final", "Winners"].includes(b) ? t(`stage.${b}`, undefined, lang) : named(b);
  let text = t(key, { n: b ? second : name, name, p: second, g: second, y: a }, lang);
  if (index >= 0 && text.includes("|")) {
    const bag = text.split("|");
    return bag[index] ?? bag[0] ?? text;
  }
  return text;
}

export function pickLine(key: string, rng: () => number, lang: Lang = current): string {
  const bag = t(key, undefined, lang).split("|");
  return bag[Math.floor(rng() * bag.length)] ?? bag[0] ?? "";
}
